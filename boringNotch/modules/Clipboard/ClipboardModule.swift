import AppKit
import SwiftUI

struct ClipboardModule: NotchModule {
    let id = "clipboard"
    let label = "Copies"
    let icon = "doc.on.clipboard"

    func start() { Task { @MainActor in ClipboardStore.shared.start() } }

    @MainActor func makeView() -> AnyView { AnyView(ClipboardView()) }
}

struct Clip: Identifiable {
    enum Content {
        case text(String)
        case image(NSImage)
        case files([URL])
    }
    let id = UUID()
    let content: Content
    let date: Date

    var preview: String {
        switch content {
        case .text(let s): s.trimmingCharacters(in: .whitespacesAndNewlines).components(separatedBy: .newlines).first ?? ""
        case .image(let i): "Image \(Int(i.size.width))×\(Int(i.size.height))"
        case .files(let u): u.map(\.lastPathComponent).joined(separator: ", ")
        }
    }
    var symbol: String {
        switch content {
        case .text: "text.alignleft"
        case .image: "photo"
        case .files: "doc"
        }
    }
    /// Même contenu (pour ne pas empiler deux fois la même copie).
    func same(as other: Content) -> Bool {
        switch (content, other) {
        case let (.text(a), .text(b)): a == b
        case let (.files(a), .files(b)): a == b
        case let (.image(a), .image(b)): a.tiffRepresentation == b.tiffRepresentation
        default: false
        }
    }
}

@MainActor
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()
    static let limit = 5

    @Published private(set) var clips: [Clip] = []
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Convention nspasteboard.org : 1Password, Bitwarden, etc. marquent ainsi les mots de passe copiés.
    private static let secret: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
    ]

    // ponytail: macOS ne notifie pas les copies ; lecture de changeCount (un entier) toutes les 0,5 s.
    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            Task { @MainActor in ClipboardStore.shared.poll() }
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard Set(pb.types ?? []).isDisjoint(with: Self.secret), let content = Self.read(pb) else { return }
        clips.removeAll { $0.same(as: content) }
        clips.insert(Clip(content: content, date: .now), at: 0)
        if clips.count > Self.limit { clips.removeLast(clips.count - Self.limit) }
    }

    private static func read(_ pb: NSPasteboard) -> Clip.Content? {
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return .files(urls)
        }
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return .text(repaired(s)) }
        if let img = NSImage(pasteboard: pb) { return .image(img) }
        return nil
    }

    /// Texte UTF-8 lu comme du Mac Roman (« consid√®re », « ‚Äî ») : c'est ce que produit `pbcopy` lancé sans
    /// locale UTF-8. On le recode ; un texte normal ne redevient presque jamais de l'UTF-8 valide et reste tel quel.
    static func repaired(_ s: String) -> String {
        guard s.unicodeScalars.contains(where: { $0.value > 0x7F }),
              let bytes = s.data(using: .macOSRoman), let fixed = String(data: bytes, encoding: .utf8) else { return s }
        return fixed
    }

    /// Remet la copie dans le presse-papiers ; `paste` simule ⌘V dans l'app au premier plan
    /// (la fenêtre du notch ne prend jamais le focus, l'app d'avant reste devant).
    func use(_ clip: Clip, paste: Bool) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch clip.content {
        case .text(let s): pb.setString(s, forType: .string)
        case .image(let i): pb.writeObjects([i])
        case .files(let u): pb.writeObjects(u as [NSURL])
        }
        guard paste else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            let src = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let e = CGEvent(keyboardEventSource: src, virtualKey: 0x09, keyDown: down)   // V
                e?.flags = .maskCommand
                e?.post(tap: .cghidEventTap)
            }
        }
    }
}

private struct ClipboardView: View {
    @EnvironmentObject var vm: BoringViewModel
    @ObservedObject private var store = ClipboardStore.shared

    var body: some View {
        if store.clips.isEmpty {
            Text("Rien de copié depuis le lancement de l'app")
                .font(.system(size: 11)).foregroundStyle(.gray)
                .frame(maxWidth: .infinity, maxHeight: .infinity)
        } else {
            TimelineView(.periodic(from: .now, by: 30)) { t in
                VStack(spacing: 3) {
                    ForEach(store.clips) { row($0, now: t.date) }
                }
                .frame(maxHeight: .infinity, alignment: .top)
            }
            .padding(.horizontal, 6)
        }
    }

    private func row(_ clip: Clip, now: Date) -> some View {
        Button {
            store.use(clip, paste: NSEvent.modifierFlags.contains(.option))
            vm.close()
        } label: {
            HStack(spacing: 9) {
                if case .image(let i) = clip.content {
                    Image(nsImage: i).resizable().scaledToFill().frame(width: 18, height: 18)
                        .clipShape(RoundedRectangle(cornerRadius: 4))
                } else {
                    Image(systemName: clip.symbol).font(.system(size: 10)).foregroundStyle(.gray).frame(width: 18)
                }
                Text(clip.preview).font(.system(size: 11.5)).foregroundStyle(.white).lineLimit(1).truncationMode(.tail)
                Spacer(minLength: 8)
                Text(Self.age(now.timeIntervalSince(clip.date))).font(.system(size: 10).monospacedDigit()).foregroundStyle(.gray)
            }
            .padding(.horizontal, 9).frame(height: 24)
            .background(RoundedRectangle(cornerRadius: 8, style: .continuous).fill(.white.opacity(0.06)))
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .help("Clic : copier · ⌥-clic : copier et coller")
    }

    static func age(_ t: TimeInterval) -> String {
        let m = Int(t / 60)
        if m < 1 { return "à l'instant" }
        if m < 60 { return "\(m) min" }
        return m < 1440 ? "\(m / 60) h" : "\(m / 1440) j"
    }
}
