import AppKit
import SwiftUI

struct ClipboardModule: NotchModule {
    let id = "clipboard"
    let label = "Copies"
    let icon = "doc.on.clipboard"

    func start() { Task { @MainActor in ClipboardStore.shared.start() } }

    @MainActor func makeView() -> AnyView { AnyView(ClipboardView()) }
}

@MainActor
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()
    static let limit = 5
    static let maxPinned = limit - 1   // garde toujours une place pour la dernière copie

    @Published private(set) var clips: [Clip] = []
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Convention nspasteboard.org : 1Password, Bitwarden, etc. marquent ainsi les mots de passe copiés.
    private static let secret: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
    ]

    // ponytail: macOS ne notifie pas les copies ; lecture de changeCount (un entier) toutes les 0,5 s.
    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { _ in
            Task { @MainActor in ClipboardStore.shared.poll() }
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard Set(pb.types ?? []).isDisjoint(with: Self.secret), let content = Self.read(pb) else { return }
        // Déjà épinglée (ou recopiée depuis son épingle) : elle reste où elle est.
        if clips.contains(where: { $0.pinned && $0.same(as: content) }) { return }
        clips.removeAll { $0.same(as: content) }
        clips = ([Clip(content: content, date: .now)] + clips).arranged(limit: Self.limit)
    }

    var pinnedCount: Int { clips.filter(\.pinned).count }

    // ponytail: épingles en mémoire seulement, comme l'historique (rien sur disque) ; elles s'effacent en quittant l'app.
    func togglePin(_ clip: Clip) {
        guard let i = clips.firstIndex(where: { $0.id == clip.id }) else { return }
        if !clips[i].pinned, pinnedCount >= Self.maxPinned { return }
        var pinned = clips.filter(\.pinned)
        var item = clips[i]
        item.pinned.toggle()
        if item.pinned { pinned.append(item) } else { pinned.removeAll { $0.id == item.id } }
        clips = (pinned + clips.filter { !$0.pinned && $0.id != item.id } + (item.pinned ? [] : [item])).arranged(limit: Self.limit)
    }

    private static func read(_ pb: NSPasteboard) -> Clip.Content? {
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return .files(urls)
        }
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { return .text(repaired(s)) }
        if let img = NSImage(pasteboard: pb) { return .image(img) }
        return nil
    }

    /// Texte UTF-8 lu comme du Mac Roman (« consid√®re », « ‚Äî ») : c'est ce que produit `pbcopy` lancé sans
    /// locale UTF-8. On le recode ; un texte normal ne redevient presque jamais de l'UTF-8 valide et reste tel quel.
    static func repaired(_ s: String) -> String {
        guard s.unicodeScalars.contains(where: { $0.value > 0x7F }),
              let bytes = s.data(using: .macOSRoman), let fixed = String(data: bytes, encoding: .utf8) else { return s }
        return fixed
    }

    /// Remet la copie dans le presse-papiers ; `paste` simule ⌘V dans l'app au premier plan
    /// (la fenêtre du notch ne prend jamais le focus, l'app d'avant reste devant).
    func use(_ clip: Clip, paste: Bool) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch clip.content {
        case .text(let s): pb.setString(s, forType: .string)
        case .image(let i): pb.writeObjects([i])
        case .files(let u): pb.writeObjects(u as [NSURL])
        }
        guard paste else { return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) {
            let src = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let e = CGEvent(keyboardEventSource: src, virtualKey: 0x09, keyDown: down)   // V
                e?.flags = .maskCommand
                e?.post(tap: .cghidEventTap)
            }
        }
    }
}

private struct ClipboardView: View {
    @EnvironmentObject var vm: BoringViewModel
    @ObservedObject private var store = ClipboardStore.shared

    var body: some View {
        VStack(spacing: 7) {
            if store.clips.isEmpty {
                emptyState
            } else {
                GeometryReader { geometry in
                    TimelineView(.periodic(from: .now, by: 30)) { timeline in
                        HStack(spacing: 8) {
                            ForEach(store.clips) { clip in
                                ClipboardCard(clip: clip, now: timeline.date,
                                              canPin: clip.pinned || store.pinnedCount < ClipboardStore.maxPinned,
                                              onPin: { withAnimation(.smooth(duration: 0.25)) { store.togglePin(clip) } }) {
                                    store.use(clip, paste: NSEvent.modifierFlags.contains(.option))
                                    vm.close()
                                }
                                // Give sparse histories more room without stretching one copy across the notch.
                                .frame(width: cardWidth(in: geometry.size.width))
                            }
                        }
                        .frame(maxHeight: .infinity)
                    }
                }
            }
            footer
        }
        .padding(.horizontal, 4)
    }

    private func cardWidth(in width: CGFloat) -> CGFloat {
        let columns = max(3, store.clips.count)
        return max(0, (width - CGFloat(columns - 1) * 8) / CGFloat(columns))
    }

    private var emptyState: some View {
        HStack(spacing: 14) {
            Image(systemName: "doc.on.clipboard")
                .font(.system(size: 25, weight: .light))
                .foregroundStyle(Color.effectiveAccent)
                .frame(width: 48, height: 48)
                .background(Color.effectiveAccent.opacity(0.12), in: RoundedRectangle(cornerRadius: 13))
            VStack(alignment: .leading, spacing: 5) {
                Text("Vos prochaines copies, juste ici")
                    .font(.system(size: 13, weight: .semibold))
                    .foregroundStyle(.white)
                Text("Copiez du texte, une image ou un fichier avec ⌘C.")
                    .font(.system(size: 11))
                    .foregroundStyle(.white.opacity(0.65))
            }
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity)
    }

    private var footer: some View {
        HStack(spacing: 4) {
            if store.clips.isEmpty {
                Label("Historique en mémoire uniquement", systemImage: "lock")
            } else {
                if store.pinnedCount > 0 {
                    Label("\(store.pinnedCount) épinglée\(store.pinnedCount > 1 ? "s" : "")", systemImage: "pin.fill")
                    Text("·").padding(.horizontal, 3)
                }
                Text("\(store.clips.count - store.pinnedCount) récente\(store.clips.count - store.pinnedCount > 1 ? "s" : "")")
                Spacer(minLength: 8)
                Text("Clic : copier")
                Text("·").padding(.horizontal, 3)
                Text("⌥ clic : coller")
            }
        }
        .font(.system(size: 10))
        .foregroundStyle(.white.opacity(0.6))
        .frame(maxWidth: .infinity, alignment: .center)
        .padding(.horizontal, 2)
    }
}

/// A copy is its own preview and hit target; the content never takes keyboard focus.
private struct ClipboardCard: View {
    let clip: Clip
    let now: Date
    let canPin: Bool
    let onPin: () -> Void
    let action: () -> Void
    @State private var hovering = false
    @Environment(\.accessibilityReduceMotion) private var reduceMotion

    private var link: URL? {
        guard case .text(let text) = clip.content else { return nil }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: { $0.isWhitespace }),
              let url = URL(string: trimmed),
              ["https", "http"].contains(url.scheme?.lowercased() ?? ""),
              url.host != nil else { return nil }
        return url
    }

    private var kind: String {
        switch clip.content {
        case .text: link == nil ? "Texte" : "Lien"
        case .image: "Image"
        case .files(let files): files.count > 1 ? "Fichiers" : "Fichier"
        }
    }

    private var fullPreview: String {
        if case .text(let text) = clip.content {
            return text.trimmingCharacters(in: .whitespacesAndNewlines)
        }
        return clip.preview
    }

    private var tint: Color {
        switch clip.content {
        case .text: link == nil ? .white.opacity(0.7) : .cyan
        case .image: Color(red: 0.78, green: 0.65, blue: 1)
        case .files: .orange
        }
    }

    var body: some View {
        Button(action: action) {
            VStack(alignment: .leading, spacing: 7) {
                HStack(spacing: 4) {
                    Image(systemName: link == nil ? clip.symbol : "link")
                    Text(kind)
                    Spacer(minLength: 18)   // place de l'épingle
                }
                .font(.system(size: 9.5, weight: .medium))
                .foregroundStyle(tint)

                preview
                    .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
                    .clipped()

                HStack(spacing: 2) {
                    Text(Self.age(now.timeIntervalSince(clip.date)))
                        .lineLimit(1)
                        .monospacedDigit()
                    Spacer(minLength: 0)
                    Image(systemName: "doc.on.doc")
                        .foregroundStyle(Color.effectiveAccent)
                        .opacity(hovering ? 1 : 0)
                }
                .font(.system(size: 9))
                .foregroundStyle(.white.opacity(0.6))
            }
            .padding(10)
            .frame(maxWidth: .infinity, maxHeight: .infinity)
            .background(.white.opacity(hovering ? 0.11 : 0.065), in: RoundedRectangle(cornerRadius: 11))
            .overlay {
                RoundedRectangle(cornerRadius: 11)
                    .strokeBorder(hovering ? Color.effectiveAccent.opacity(0.65)
                                  : clip.pinned ? Color.effectiveAccent.opacity(0.3) : .white.opacity(0.08))
            }
            .contentShape(RoundedRectangle(cornerRadius: 11))
        }
        .buttonStyle(.plain)
        // Bouton frère de la carte (pas imbriqué) : son clic n'enclenche pas la copie.
        .overlay(alignment: .topTrailing) {
            if clip.pinned || hovering {
                Button(action: onPin) {
                    Image(systemName: clip.pinned ? "pin.fill" : "pin")
                        .font(.system(size: 9.5, weight: .semibold))
                        .rotationEffect(.degrees(45))
                        .foregroundStyle(clip.pinned ? Color.effectiveAccent : .white.opacity(0.75))
                        .frame(width: 22, height: 22)
                        .contentShape(Rectangle())
                }
                .buttonStyle(.plain)
                .disabled(!canPin)
                .opacity(canPin ? 1 : 0.35)
                .padding(4)
                .help(clip.pinned ? "Détacher" : canPin ? "Épingler : reste ici malgré les nouvelles copies"
                                                         : "\(ClipboardStore.maxPinned) épingles au maximum")
                .accessibilityLabel(clip.pinned ? "Détacher" : "Épingler")
                .transition(.opacity)
            }
        }
        .contextMenu {
            Button(clip.pinned ? "Détacher" : "Épingler", action: onPin).disabled(!canPin)
        }
        .accessibilityAction(named: clip.pinned ? "Détacher" : "Épingler", onPin)
        .onHover { hovering = $0 }
        .animation(reduceMotion ? nil : .easeOut(duration: 0.15), value: hovering)
        .help("\(String(fullPreview.prefix(1000)))\nClic : copier · ⌥-clic : copier et coller")
        .accessibilityLabel("\(kind) : \(fullPreview)")
        .accessibilityHint("Copier. Option-clic pour coller dans l’application active.")
    }

    @ViewBuilder private var preview: some View {
        switch clip.content {
        case .text(let text):
            if let link {
                VStack(alignment: .leading, spacing: 4) {
                    Text(link.host ?? "")
                        .font(.system(size: 11, weight: .semibold))
                        .foregroundStyle(.white)
                        .lineLimit(1)
                        .minimumScaleFactor(0.85)
                        .truncationMode(.middle)
                    Text(link.path.isEmpty || link.path == "/" ? "Page web" : link.path)
                        .font(.system(size: 10))
                        .foregroundStyle(.white.opacity(0.65))
                        .lineLimit(2)
                }
            } else {
                Text(String(text.trimmingCharacters(in: .whitespacesAndNewlines).prefix(500)))
                    .font(.system(size: 11))
                    .foregroundStyle(.white.opacity(0.95))
                    .lineLimit(4)
                    .multilineTextAlignment(.leading)
            }
        case .image(let image):
            GeometryReader { geometry in
                Image(nsImage: image)
                    .resizable()
                    .scaledToFit()
                    .frame(width: geometry.size.width, height: geometry.size.height)
                    .background(.white.opacity(0.04))
                    .clipShape(RoundedRectangle(cornerRadius: 5))
            }
        case .files(let files):
            VStack(alignment: .leading, spacing: 4) {
                Text(files.first?.lastPathComponent ?? "Fichier")
                    .font(.system(size: 11, weight: .medium))
                    .foregroundStyle(.white.opacity(0.95))
                    .lineLimit(2)
                    .truncationMode(.middle)
                if files.count > 1 {
                    Text("+ \(files.count - 1) autre\(files.count > 2 ? "s" : "")")
                        .font(.system(size: 10))
                        .foregroundStyle(.white.opacity(0.65))
                }
            }
        }
    }

    static func age(_ t: TimeInterval) -> String {
        let m = Int(t / 60)
        if m < 1 { return "à l'instant" }
        if m < 60 { return "\(m) min" }
        return m < 1440 ? "\(m / 60) h" : "\(m / 1440) j"
    }
}
